/**
 * Representative sample documents and templates. All content is fictional.
 * PDFs are generated deterministically (fixed metadata dates) so fixtures and
 * their hashes are stable across runs.
 */

const FIXED_DATE = new Date('2026-01-01T00:00:00Z');

async function textPdf(title: string, pages: string[][]): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setCreationDate(FIXED_DATE);
  doc.setModificationDate(FIXED_DATE);
  doc.setTitle(title);
  doc.setProducer('lomi-fixtures');
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  for (const lines of pages) {
    const page = doc.addPage([612, 792]);
    lines.forEach((line, i) => {
      const heading = i === 0;
      page.drawText(line, { x: 56, y: 730 - i * 20, size: heading ? 16 : 11, font: heading ? bold : font, color: rgb(0.1, 0.1, 0.1) });
    });
  }
  return doc.save();
}

