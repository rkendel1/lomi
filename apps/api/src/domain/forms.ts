import type { Field, FieldType } from '@lomi/core';
import type { TemplateDefinition } from '@lomi/docops';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { withTenant } from '../db/pool';
import { DomainError, type Actor, type Ctx } from './common';
import { createDocumentType, publishTemplate, saveDraft, uploadBasePdf, validateDefinition } from './templates';

/**
 * Quick form setup: a document type defined by the list of things to read
 * from it. Lomi generates the output form (one labelled row per field) and a
 * template whose fields are read by the extraction model from their
 * plain-language instructions. Layout, rules and checks can be refined later
 * in Schema Studio like any other template.
 */

export type FormValueType = 'string' | 'date' | 'money' | 'number' | 'percent';

export interface FormFieldSpec {
  /** What a person calls it, e.g. "Invoice number". */
  label: string;
  type: FormValueType;
  /** What to look for, in plain words; defaults to the label. */
  instructions?: string;
  required?: boolean;
  /** Snake-case name; derived from the label when omitted. */
  key?: string;
}

const FIXED_DATE = new Date('2026-01-01T00:00:00Z');
export const MAX_FORM_FIELDS = 20;
export const TYPE_KEY = /^[a-z][a-z0-9_]{0,62}$/;

export const formRowY = (i: number) => 670 - i * 28;
export const toKey = (text: string) => text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').replace(/^(\d)/, 'f_$1');

/** A blank output form; templates place approved values onto it. Deterministic bytes. */
export async function outputFormPdf(title: string, labels: string[]): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setCreationDate(FIXED_DATE);
  doc.setModificationDate(FIXED_DATE);
  doc.setProducer('lomi-fixtures');
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const page = doc.addPage([612, 792]);
  page.drawText(title, { x: 56, y: 730, size: 16, font: bold });
  page.drawText('Generated by Lomi Document Operations from approved values', { x: 56, y: 712, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
  labels.forEach((label, i) => {
    const y = formRowY(i);
    page.drawText(label, { x: 56, y: y + 3, size: 10, font });
    page.drawRectangle({ x: 218, y: y - 2, width: 330, height: 16, borderColor: rgb(0.7, 0.7, 0.7), borderWidth: 0.5 });
  });
  return doc.save();
}

/** One model-read field placed on row `i` of the generated output form. */
export function formField(typeKey: string, i: number, spec: { key: string; label: string; type: FormValueType; instructions: string; required?: boolean }): Field {
  const type: FieldType = spec.type === 'date' ? 'date' : spec.type === 'money' ? 'currency' : 'text';
  const sourceFieldId = `${typeKey}_${spec.key}`;
  return {
    id: sourceFieldId,
    name: sourceFieldId,
    sourceFieldId,
    semanticKey: `${typeKey}.${spec.key}`,
    displayLabel: spec.label,
    page: 0,
    x: 222,
    y: formRowY(i),
    width: 320,
    height: 14,
    type,
    fontSize: 10,
    maxWidth: 320,
    ...(spec.required ? { required: true } : {}),
    ...(spec.type === 'number' ? { dataType: 'number' as const } : {}),
    ...(type === 'date' ? { transformType: 'date' as const, dateFormat: 'YYYY-MM-DD' as const } : {}),
    ...(type === 'currency' ? { transformType: 'currency' as const, currencySymbol: 'USD' as const } : {}),
    extraction: { method: 'llm', instructions: spec.instructions, valueType: spec.type },
    validationRules: spec.type === 'percent' ? [{ kind: 'regex' as const, pattern: '^\\d+(\\.\\d+)?%$', message: 'Expected a percentage such as 4.2%.' }] : [],
  };
}

/** Validate and normalize a quick-form request without writing anything. */
export function planForm(input: { key?: string; name: string; fields: FormFieldSpec[] }) {
  const name = input.name.trim();
  if (!name) throw new DomainError('INVALID_INPUT', 'Give the form a name, e.g. "Purchase order".');
  const key = (input.key?.trim() || toKey(name)).slice(0, 63);
  if (!TYPE_KEY.test(key)) throw new DomainError('INVALID_INPUT', `"${key}" is not a valid form key: use lowercase letters, digits and _ , starting with a letter.`);
  const specs = input.fields.filter((f) => f.label?.trim());
  if (specs.length === 0) throw new DomainError('INVALID_INPUT', 'Add at least one field to read from the document.');
  if (specs.length > MAX_FORM_FIELDS) throw new DomainError('INVALID_INPUT', `A quick form can have at most ${MAX_FORM_FIELDS} fields; add more in Schema Studio.`);
  const seen = new Set<string>();
  const fields = specs.map((f, i) => {
    const fieldKey = (f.key?.trim() || toKey(f.label)).slice(0, 63);
    if (!fieldKey) throw new DomainError('INVALID_INPUT', `Field "${f.label}" needs a name with letters or digits.`);
    if (seen.has(fieldKey)) throw new DomainError('INVALID_INPUT', `Two fields would both be called "${fieldKey}"; rename one.`);
    seen.add(fieldKey);
    return formField(key, i, { key: fieldKey, label: f.label.trim(), type: f.type, instructions: f.instructions?.trim() || f.label.trim().toLowerCase(), required: f.required });
  });
  const definition: TemplateDefinition = { fields, crossFieldRules: [], identityKeys: [] };
  const problems = validateDefinition(definition);
  if (problems.length) throw new DomainError('INVALID_INPUT', 'The form has problems.', { problems });
  return { key, name, definition };
}

/**
 * Create a document type with a generated output form and a template, and
 * (by default) publish it so documents of this type can be submitted now.
 * Everything is validated before anything is written.
 */
export async function createForm(
  ctx: Ctx,
  actor: Actor,
  input: { tenantId: string; key?: string; name: string; description?: string; fields: FormFieldSpec[]; publish?: boolean }
) {
  const plan = planForm(input);
  const taken = await withTenant(ctx.db, input.tenantId, async (tx) => (await tx.query('SELECT 1 FROM document_types WHERE tenant_id = $1 AND key = $2', [input.tenantId, plan.key])).rows[0]);
  if (taken) throw new DomainError('CONFLICT', `A form with the key "${plan.key}" already exists for this customer.`);
  const bytes = await outputFormPdf(`${plan.name} — approved values`, plan.definition.fields.map((f) => f.displayLabel));

  const type = await createDocumentType(ctx, actor, { tenantId: input.tenantId, key: plan.key, name: plan.name, description: input.description?.trim() || undefined });
  const base = await uploadBasePdf(ctx, actor, { tenantId: input.tenantId, documentType: plan.key, filename: `${plan.key}-output-form.pdf`, bytes });
  const draft = await saveDraft(ctx, actor, { tenantId: input.tenantId, documentType: plan.key, definition: plan.definition, basePdfId: base.id, notes: 'Created with quick form setup' });
  const published = input.publish === false ? null : await publishTemplate(ctx, actor, { tenantId: input.tenantId, templateVersionId: draft.id });
  return {
    documentType: { id: type.id, key: plan.key, name: plan.name },
    templateVersionId: draft.id,
    version: draft.version,
    status: published ? 'published' : 'draft',
    fields: plan.definition.fields.map((f) => ({ key: f.semanticKey, label: f.displayLabel })),
  };
}
